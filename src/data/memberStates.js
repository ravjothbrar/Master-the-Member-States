// Helper function to get flag URL from flagcdn.com
export const getFlagUrl = (code, size = 'w160') => {
  return `https://flagcdn.com/${size}/${code}.png`;
};

// Helper function to shuffle an array (Fisher-Yates algorithm)
export const shuffleArray = (array) => {
  const shuffled = [...array];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled;
};

// Generate quiz questions
export const generateQuestions = (count, mode, states = memberStates) => {
  const shuffledStates = shuffleArray(states);
  const questionStates = count === 'all' ? shuffledStates : shuffledStates.slice(0, parseInt(count));

  return questionStates.map((correctState, index) => {
    // Determine question type based on mode
    let questionType;
    if (mode === 'mixed') {
      questionType = Math.random() > 0.5 ? 'flagToName' : 'nameToFlag';
    } else {
      questionType = mode === 'flagToName' ? 'flagToName' : 'nameToFlag';
    }

    // Get 4 random distractors (different from correct answer)
    const otherStates = states.filter(s => s.code !== correctState.code);
    const distractors = shuffleArray(otherStates).slice(0, 4);

    // Combine correct answer with distractors and shuffle
    const options = shuffleArray([correctState, ...distractors]);

    return {
      id: index + 1,
      type: questionType,
      correctAnswer: correctState,
      options,
    };
  });
};
